                                    <h3 class="c-h3-a__text">Corporate governance system under the business unit structure</h3>
                                </div>
                            </div>
                                                    <div class="c-linkCard__textwrap">
                                <div class="c-text-a">
  <p class="c-text-a__text">On April 1, 2021, the Ricoh Group shifted to a business unit structure in order to transform our business structure into a digital services company and further improve returns on capital. Each business unit and headquarters focus on the following functions to improve the Group's overall corporate value.</p>
  <dl class="c-list-inline-a u-mt-8">
    <dt class="u-mr-8">Business Units:</dt>
    <dd>Autonomous business operations led by the business unit president</dd>
  </dl>
  <dl class="c-list-inline-a u-mt-8">
    <dt class="u-mr-8">Group headquarters:</dt>
    <dd>Planning of medium- to long-term strategies for the entire Group and capital allocation to each business unit Strict business management based on growth potential and return on capital Optimization of cross-functional, expertise, and company-wide perspectives</dd>
  </dl>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Based on the adoption of the business unit structure, we are proceeding with the following governance-related initiatives from the perspectives of oversight, execution, and audit:</p>
  <ol>
    <li><strong>Oversight</strong>
      <dl class="c-list-inline-a u-mt-8">
        <dt class="u-mr-8">a)</dt>
        <dd>Oversight of each organization's top management
          <ul class="c-list-disc-a">
            <li class="c-list-disc-a__item c-list-disc-a__item--black">The Board of Directors and the Nomination Committee have carried out performance evaluations of business unit presidents and headquarters function's executive managers.</li>
          </ul>
        </dd>
      </dl>
      <dl class="c-list-inline-a u-mt-8">
        <dt class="u-mr-8">b)</dt>
        <dd>Oversight of business performance
          <ul class="c-list-disc-a">
            <li class="c-list-disc-a__item c-list-disc-a__item--black">The Board of Directors deliberates on the performance status of each business unit on a quarterly basis and monitors invested capital and return on capital.</li>
          </ul>
        </dd>
      </dl>
      <dl class="c-list-inline-a u-mt-8">
        <dt class="u-mr-8">c)</dt>
        <dd>Strengthening of group governance and risk management
          <ul class="c-list-disc-a">
            <li class="c-list-disc-a__item c-list-disc-a__item--black">The Board of Directors is strengthening its monitoring to ensure that internal controls and risk management are functioning properly after transition to a business unit structure, including the delegation of authority to each business unit and the review of affiliate management.</li>
          </ul>
        </dd>
      </dl>
    </li>
    <li><strong>Execution</strong>
      <dl class="c-list-inline-a u-mt-8">
        <dt class="u-mr-8">a)</dt>
        <dd>Monitoring by CEO/general managers of Group headquarters
          <ul class="c-list-disc-a">
            <li class="c-list-disc-a__item c-list-disc-a__item--black">The CEO and general managers of Group headquarters monitor the status of each business unit's achievement of targets (return on capital, etc.), share timely topics, and discuss issues and countermeasures at monthly business unit management meetings.</li>
          </ul>
        </dd>
      </dl>
      <dl class="c-list-inline-a u-mt-8">
        <dt class="u-mr-8">b)</dt>
        <dd>Conducting portfolio management meetings<sup>*</sup> (annually)
