            <li class="c-list-disc-a__item c-list-disc-a__item--black">Compensation for Internal Directors who do not concurrently serve as Executive Officers is comprised of basic compensation, bonuses and stock-based compensation in light of their role of overseeing business execution as full-time Director with extensive knowledge of the actual situation of the Company.</li>
