  <p class="c-text-a__text">The Company will continue to emphasize the enhancement of shareholder value and corporate value over the medium to long term. It will further increase the ratio of variable compensation linked to shareholder value and business performance. Additionally, it will continue to evaluate the appropriate amount of compensation for each compensation type.</p>
