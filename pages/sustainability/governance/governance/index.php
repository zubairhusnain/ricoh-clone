<div class="c-h5-a u-mb-0">
  <h5 class="c-h5-a__text">Process for determining compensation</h5>
</div>
<div class="c-text-a u-mt-0">
  <p class="c-text-a__text">The Company has established a voluntary Compensation Committee to build a more objective and transparent compensation review process that contributes to increasing profits, enhance corporate value, and strengthen corporate governance through incentives. The Compensation Committee determines each compensation plan for basic compensation, bonuses, compensation for acquiring stock, and performancelinked stock-based compensation after multiple deliberations based on the compensation standards for Directors and business performance, as well as the results of the Nomination Committee's evaluation of Directors, and makes recommendations to the Board of Directors.</p>
  <p class="c-text-a__text">The Board of Directors deliberates on and decides each compensation plan recommended by the Compensation Committee. With respect to bonuses, the Board of Directors determines the total amount of bonuses to be paid after confirming that the amount of bonuses for each individual Director is appropriate in accordance with the formula for Directors' bonuses, and decides on a proposal for the payment of bonuses to Directors and whether or not to submit the proposal to the General Meeting of Shareholders. After the proposal for payment of bonuses to Directors is approved at the General Meeting of Shareholders, the amount of the individual bonuses determined by the Board of Directors is paid.</p>
