<div class="c-text-a u-mt-8">
  <p class="c-text-a__text">Regarding performance-linked stock-based compensation, a malus clause and a clawback clause are stipulated in the rules governing performance shares determined by the Board of Directors of the Company. In the event that a Director engages in serious misconduct, etc. that negatively impacts the Company, all or part of the points granted up to that time will be nullified by a resolution of the Board of Directors and the Director subject to the malus clause and the clawback clause will not be eligible for beneficiary rights related to the nullified points.</p>
  <p class="c-text-a__text">Furthermore, the Company can demand that those who have already received delivery of Company Shares and delivery of money in lieu of Company Shares to return the amount obtained by multiplying the total number of points by the closing price of the Company Shares on the Tokyo Stock Exchange on the date such request is made.</p>
