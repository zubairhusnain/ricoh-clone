        <li>A person who is not a shareholder holding 10% or more of the total voting rights of the Company (a “major shareholder”), or a person who is not a director, audit and supervisory board member, accounting advisor, executive officer, executive director, corporate officer, manager or any other employee of the major shareholder of the Company.</li>
        <li>A person who is not a director, audit and supervisory board member, accounting advisor, executive officer, executive director, corporate officer, manager or any other employee of a company of which the Ricoh Group is a major shareholder.</li>
        <li>A person who is not a director, audit and supervisory board member, accounting advisor, executive officer, executive director, corporate officer, manager or any other employee of the Ricoh Group, or a person who was not a director, audit and supervisory board member, accounting advisor, executive officer, executive director, corporate officer, manager or any other employee of the Ricoh Group within 10 years preceding the assumption of the office of Outside Directors and Outside Audit &amp; Supervisory Board Members.</li>
        <li>A person of which the Ricoh Group was not a major business partner (whose sales to the Ricoh Group accounted for 2% or more of its consolidated net sales) in the immediately preceding fiscal year or any of the three fiscal years prior to such fiscal year, or a person who is not a director (excluding outside directors who are independent), executive officer, executive director, corporate officer, manager or any other employee thereof (including its parent company and subsidiaries).</li>
        <li>A person who was not a major business partner of the Ricoh Group (to which sales of the Ricoh Group accounted for 2% or more of consolidated net sales of the Ricoh Group) in the immediately preceding fiscal year or any of the three fiscal years prior to such fiscal year, or a person who is not a director (excluding outside directors who are independent), executive officer, executive director, corporate officer, manager or any other employee thereof (including its parent company and subsidiaries).</li>
        <li>A person who is not a consultant, certified public accountant, certified tax accountant, lawyer or any other professional who received money or other property other than executive compensation, either directly or indirectly, from the Ricoh Group in an amount of ¥10 million or more in the immediately preceding fiscal year or per year in average over the past three fiscal years.</li>
        <li>A person who does not belong to an organization, such as a law firm, auditing firm, tax accounting firm, consulting firm or any other professional advisory firm, that received money or other property, either directly or indirectly, from the Ricoh Group in an amount equivalent to 2% or more of its total revenue in the immediately preceding fiscal year or per year in average over the past three fiscal years.</li>
        <li>A person who is not a spouse, a relative within the second degree of kinship or a relative who lives in the same household of a person who falls under the items (1) through (7).</li>
        <li>A person who is not a director, audit and supervisory board member, accounting advisor, executive officer, executive director, corporate officer, manager or any other important employee of a company, its parent company or subsidiary that has directors dispatched from the Ricoh Group.</li>
        <li>A person who is unlikely to cause a substantial conflict of interests with the Company.</li>
      </ol>
    </li>
    <li>The Company may appoint a person as Outside Director or Outside Audit and Supervisory Board Member if it determines that the person is qualified for the post, even though he/she fails to satisfy any of the above items (1) and (4) through (9) in the preceding paragraph, provided that the Company explains to external parties the reason for its determination that the person qualifies for the post.</li>
  </ol>
