  <div class="c-h5-a u-mb-0">
    <h5 class="c-h5-a__text">Status of Internal Audit</h5>
  </div>
  <div class="c-text-a u-mt-0">
    <p class="c-text-a__text">Internal audits are carried out through a system in which the independent and dedicated Internal Audit Office at the headquarters (comprising 21 members as of the end of March 2025) collaborates with the organization in charge of audits at each global location. Based on the Internal Audit Standard and the Annual Audit Plan, internal audits are conducted on the Ricoh Group's business execution with a risk approach from the viewpoints of legal compliance, effectiveness and efficiency of operations, reliability of reporting, and safeguarding of assets. The Internal Audit Office provides advice and recommendations for improvement from a fair and objective standpoint. The results of internal audits are shared in written audit reports with the heads of audited entities and related sections upon completion of each audit. A summary of audit results is reported quarterly to the Internal Control Committee and the Audit &amp; Supervisory Board, and semi-annually to the Board of Directors. The Internal Audit Office has constructed and operates this dual reporting system, which directly reports to the Board of Directors and the Audit &amp; Supervisory Board. Additionally, the Internal Audit Office also evaluates and reports on internal control related to financial reporting under the Financial Instruments and Exchange Act.</p>
    <p class="c-text-a__text">Matters identified in these audits are also reported quarterly to the Supervising Organizations and the risk management division. The Ricoh Group reviews these matters for improvement and ensures necessary actions are taken. Through this follow-up cycles, it strives to enhance internal control and improve the quality of business operations.</p>
