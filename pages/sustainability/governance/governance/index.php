                                <div class="c-text-a">
  <p class="c-text-a__text">The Board of Directors reflected on Ricoh's founding principles and discussed the ideas and principles of the Board of Directors and the Directors, which are the basis for deliberations, decisions, and actions that contribute to enhancing corporate value. It accordingly established the “Board Culture,” which should be maintained and cultivated by itself explicitly as follows.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">The Board of Directors shall:</p>
  <ol class="u-pt-0">
    <li>Honor the Spirit of Three Loves, engaging with and respecting the interests of shareholders, customers, employees, partner companies, communities and society, and other stakeholders while overseeing management strategies and plans that help resolve social issues.</li>
    <li>The chairperson shall objectively lead diverse and highly independent Board members in engaging and constructive deliberations that value a diversity of open and free viewpoints. Management shall faithfully reflect the results of deliberations.</li>
    <li>Board members shall understand their social responsibilities, make robust decisions for the future, and oversee management's implementation of decisions, so Ricoh can enhance medium- and long-term corporate value by delivering exceptional business growth, capital profitability, and ESG performances.</li>
  </ol>
