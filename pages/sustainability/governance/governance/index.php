<div class="c-text-a u-mt-8">
  <p class="c-text-a__text">In the event of a significant change in the business environment, sudden deterioration of business performance, and quality issues that may damage corporate value, serious accidents, scandals, etc., the compensation for Directors may be temporarily reduced or suspended by resolution of the Board of Directors.</p>
