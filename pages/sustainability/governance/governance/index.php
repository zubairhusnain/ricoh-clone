                    <div class="c-text-a">
        <div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group is working to enhance its governance system in accordance with social awareness and various stakeholders aimed at strengthening competitiveness and continuously improving the system while ensuring transparency based on corporate ethics and legal compliance. In this way, the Ricoh Group will achieve continuous growth, and improve corporate value and shareholder value.</p>
  <p class="c-text-a__text">The Ricoh Group established The Ricoh Way as a set of guiding principles and values that serve as the foundation for all our business activities. The Ricoh Way, which comprises our founding principles, Mission &amp; Vision, and Values, is the foundation of our management policy and strategy, and also is the basis of its autonomous corporate governance.</p>
  <p class="c-text-a__text">The Company has introduced a corporate audit system. In addition, the Company is making efforts to enhance oversight of executive management by the Board of Directors and enhance execution of operations by the executive officer system. Furthermore, by appointing Outside Directors, the Company is making efforts toward further improvement of corporate governance by decision-making and oversight of executive management through discussion from their independent perspectives.</p>
  <p class="c-text-a__text">The nomination and compensation of Directors and Executive Officers are deliberated by the Nomination Committee and the Compensation Committee, advisory bodies that are comprised of a majority of Independent Outside Directors. The recommendations of each committee are reported to the Board of Directors.</p>
