<div class="c-text-a u-mt-0">
  <p class="c-text-a__text">(Performance-linked stock-based compensation)</p>
  <p class="c-text-a__text">The performance-linked stock-based compensation (the “Plan”) is a plan under which the Board Incentive Plan Trust (hereinafter referred to as the “Trust”) funded by the Company acquires the Company's common stock (“Company Shares”) from the stock market (including off-floor trading) and delivers the number of Company Shares equivalent to the number of points granted by the Company to each Director through the Trust. In principle, Directors will receive Company Shares after the completion of each period subject to performance evaluation (each period of three consecutive fiscal years commencing on April 1 of each year). The number of points granted to each Director by the Company will be determined based on the base amount for each job grade in accordance with rules governing performance shares determined by resolution of the Board of Directors and will vary between 0% to 200% by taking into account the evaluation of the Company's TSR relative to the TOPIX (including dividends) TSR growth rate as well as its ranking relative to the TSR of the peer group, and the degree of achievement of ESG targets during the performance evaluation period. Company Shares will be delivered at a rate of one share per point. In addition, preissuance malus-clawback clause has been established to demand the return of stock-based compensation in the event of serious misconduct, etc. that causes an impact on the Company during the Director's term of office.</p>
  <p class="c-text-a__text">The Plan was introduced on September 1, 2023 following a partial amendment to the stock-based compensation plan with stock price conditions resolved at the 123rd Ordinary General Meeting of Shareholders held on June 23, 2023. For the plan before the amendments, in principle, the Company will stop granting new points after September 1, 2023, and the number of Company Shares corresponding to the accumulated points will be delivered at retirement in accordance with the provisions of the plan before the amendments. The amount of expenses recorded based on the points granted for the fiscal 2023 under the Plan before the amendments was ¥74.13 million, and shares (8,400 shares) were granted to an internal Director who retired during fiscal 2023 in proportion to the result of the comparison of the Company's stock price growth rate (103.7%) with TOPIX growth rate (138.0%) during the tenure of the Director to the accumulated points (the indicator was selected to have Directors share with shareholders the benefits and risks arising from fluctuations in the stock price).</p>
