            <div class="c-margin-b__inner">
                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Relationship between executive compensation and ESG indicators</h2>
                    </div>
                <div class="c-text-a" style="max-width: 100%;">
  <p class="c-text-a__text">To clarify management's responsibility for ESG initiatives and achieving targets, we have
    incorporated ESG indicators into executive compensation since the fiscal year 2020.</p>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Relationship to Executive Bonuses</h3>
</div>

<div class="c-text-a" style="max-width: 100%;">
  <p class="c-text-a__text">By incorporating the "DJSI* Annual Ratings," which are used as a tool to monitor ESG
    initiatives, into the performance-based bonus calculation formula for directors and executive officers, we provide
    incentives for ESG initiatives. Furthermore, executive officers' compensation is also linked to ESG goals within
    their areas of responsibility, enhancing commitment to achieving ESG targets in each business unit and group
    headquarters.<br><br>
    <sup>*</sup> The Dow Jones Sustainability Index (DJSI) is a share index jointly developed by Dow Jones in the US and
    S&amp;P Global, a company specializing in research on sustainable investment, to measure the sustainability of major
    companies around the world from the three perspectives of economy, environment, and society.
  </p>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Relationship to Executive Stock Compensation</h3>
</div>

<div class="c-text-a" style="max-width: 100%;">
  <p class="c-text-a__text">Starting from the fiscal year 2023, in addition to bonuses, we have introduced
    performance-based stock compensation with ESG targets for directors. The number of ESG targets achieved by the
    company is linked to the payment rate. Furthermore, this system will also be introduced for executive officers from
    the fiscal year 2024.</p>
</div>

<div class="c-h2-a" id="section05">
  <h2 class="c-h2-a__text">Approach to Materiality (Material issues)</h2>
</div>

<div class="c-text-a" style="max-width: 100%;">
  <p class="c-text-a__text">The Ricoh Group’s policy is to “align ESG with business growth.” By leveraging our
    strengths, we will further drive business growth through our initiatives. We are pleased to introduce the Ricoh
    Group’s efforts to help resolve social issues through our business activities.</p>
</div>

