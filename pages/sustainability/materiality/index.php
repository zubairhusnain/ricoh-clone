                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Materiality Analysis</h2>
                    </div>
                <div class="c-text-a">
	<div class="c-h3-a">
		<h3 class="c-h3-a__text">Materiality-specific process</h3>
		</div>
		
		<div class="c-figure u-mb-40">
		<div class="c-figure__inner">
		<div class="c-figure__item u-dsp-f u-fl-align-center u-fl-justify-sa">
		<img src="/ricoh-clone/ricoh_offline/assets/www.ricoh.com/-/Media/Ricoh/Sites/com/sustainability/materiality/img/process.png" alt="画像：Materiality-specific process">
		</div>
		</div>
		</div>
		
		<div class="c-text-a">
		<p class="c-text-a__text"><strong>STEP 1: Identifying Issues</strong><br>
		In considering our mid-term management strategy, we assess the risks and business opportunities arising from changes in environmental and social trends—such as increasing demands to address climate change and human rights. At the same time, we evaluate the impact of our business activities on the environment and society, and identify key issues that require action.​</p>
		</div>
		
		<div class="c-text-a">
		<p class="c-text-a__text"><strong>STEP 2: Prioritizing Issues</strong><br>
		Prioritize the identified issues based on international guidelines such as the SDG Compass, GRI standards, and the concept of double materiality, as well as management philosophy, management and business strategies, opinions from external stakeholders, and priority management risks in line with the risk management system. The drafts of materiality and ESG targets are then prepared.</p>
		</div>
		
		<div class="c-text-a">
		<p class="c-text-a__text"><strong>Step 3: Management Decision</strong><br>
		The materiality and ESG goals are deliberated and decided upon by the ESG Committee, which consists of the CEO as the Chairman, all Internal Directors, and Executive Officers. These decisions are made in conjunction with the financial goals of the mid-term management strategy and are approved by the Board of Directors before disclosure.</p>
		</div>
		
		<div class="c-text-a">
		<p class="c-text-a__text"><strong>STEP 4: Performance Disclosure</strong><br>
		Annual performance against ESG targets is disclosed annually by the ESG Committee, after confirmation with management.</p>
		</div>
		 
		<div class="c-text-a u-dsp-f">
		<p class="c-text-a__text u-mr-100 u-sp-mr-8"><strong>Stakeholder opinions referenced</strong><br>
		Individual meetings with shareholders/investors/analysts<br>
		Feedback from large IR meetings<br>
		ESG requests from customers during negotiations<br>
		Request in ESG evaluation systems<br>
		Opinions from internal stakeholders<br>
		Dialogues with external organizations such as JCLP and JCI</p>
		
		<p class="c-text-a__text"><strong>Reference Guidelines</strong><br>
		SDGs Compass<br>
		GRI standard<br>
		European Guidelines on non-financial Reporting directive<br>
		Ministry of the Environment's Environmental Reporting Guidelines<br>
		TCFD<br>
		Ten Principles of the United Nations Global Compact<br>
		ISO26000</p>
