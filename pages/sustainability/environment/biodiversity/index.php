                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Policy/Basic Concept</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a" style="max-width: 1360px;">
  <p class="c-text-a__text">Our human society is heavily dependent on the various benefits provided by the ecosystems on the earth, and biodiversity is closely related to these ecosystems. However, we are now losing biodiversity at an unprecedented and rapid pace due to the deterioration of the natural environment. Companies are required to assess the impact of their business activities on ecosystems, prevent the loss of biodiversity, and contribute to its restoration.<br>
The Ricoh Group established the "Biodiversity Policy" in 2009, approved by the Management Committee, believing that the conservation of biodiversity would lead to the creation of a truly affluent and sustainable society. Furthermore, in 2010, we established the " Regulations on Wood Raw Materials for Ricoh Group Products" (an expansion of the "Environmental Regulations on Procurement of Paper Products" established in 2003) to prevent deforestation and to procure raw materials with due consideration for social aspects such as labor. In addition, in 2020, we set a goal of increasing the number of trees by 1 million by 2030 through forest conservation activities that both "conserve" and "increase" the number of forests. Based on these policies and regulations, we are working with various stakeholders to reduce the environmental impact of our business activities, at the same time, we are promoting efforts to maintain and enhance the regenerative capacity of the earth.</p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a" style="max-width: 1360px;">
    <p class="c-text-a__text">The Ricoh Group aims to realize a "nature positive" and "zero deforestation" society that halts the loss of biodiversity and puts it on a recovery track by 2030. To this end, we are working to understand biodiversity risks and reduce the environmental impact of our business activities in cooperation with various stakeholders, including suppliers, while at the same time maintaining and improving the Earth's regenerative capacity.</p><!-- テキストはここを編集 -->
</div>
<div class="u-mt-16 u-pt-16 u-pb-16 u-pl-16 u-pr-16" style="border: solid 1px black;">
    <div class="c-h3-a">
        <h3 class="c-h3-a__text">Biodiversity Policy</h3>
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text"><strong>Basic Policy</strong></p><!-- テキストはここを編集 -->
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text">We recognize that while we enjoy the benefits of biodiversity, our business activities also have an impact on it. As such, we actively work towards realizing a society living in harmony with nature. We also work on the conservation of biodiversity, with the understanding that biodiversity, climate change, and resource use all mutually influence each other.</p><!-- テキストはここを編集 -->
    </div>
    <a href="/ricoh-clone/ricoh_offline/assets/www.ricoh.com/-/Media/Ricoh/Sites/com/sustainability/environment/biodiversity/pdf/ricoh-group-biodiversity-policy-english.pdf/" class="c-link-a c-link-a--pdf icon-hidden">
