<div class="u-mt-16 u-pt-16 u-pb-16 u-pl-16 u-pr-16" style="border: solid 1px black;">
    <div class="c-h3-a">
        <h3 class="c-h3-a__text">Regulations for Ricoh Group products made of wood</h3>
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text">From the viewpoint of global environmental conservation and biodiversity protection, this provision must be established to confirm that the wood raw materials used in Ricoh brand products and their accessories are legally obtained with consideration for the sustainability of the place of origin in environmental and social aspects prior to the decision of procurement.</p><!-- テキストはここを編集 -->
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text"><strong>Scope of Regulation</strong></p><!-- テキストはここを編集 -->
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text">It shall apply to the following items that are made from wood procured by the Ricoh Group:</p><!-- テキストはここを編集 -->
    </div>
    <ul class="c-list-disc-a">
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Paper　(PPC paper, thermal paper, etc.)</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Items accompanying with Ricoh Group brand products (stickers, manuals, packaging material, cushion material, etc.).</li>
    </ul>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text"><strong>Requirements for raw materials provided by suppliers</strong></p><!-- テキストはここを編集 -->
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text">Confirmation of legality of wood in the country of origin at the time of production.<br>
            Wood produced from a forest where sustainable forest management is practiced without adverse environmental or social impact at the time of production.<br>
            The products delivered to the Ricoh Group do not use wood procured by a "Supplier with Problems."</p><!-- テキストはここを編集 -->
    </div>
    <a href="/ricoh-clone/ricoh_offline/assets/www.ricoh.com/-/Media/Ricoh/Sites/com/sustainability/environment/biodiversity/pdf/regulations_products_made_of_wood_en.pdf/" class="c-link-a c-link-a--pdf icon-hidden u-mt-16">
