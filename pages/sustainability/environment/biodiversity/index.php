<div class="u-mt-16 u-pt-16 u-pb-16 u-pl-16 u-pr-16" style="border: solid 1px black;">
    <div class="c-h3-a">
        <h3 class="c-h3-a__text">Paper Procurement Policy</h3>
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text">The policy is based on two criteria: "Paper* Standards" and "Supplier Standards."</p><!-- テキストはここを編集 -->
    </div>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text"><strong>Paper Standards(Requirements to procure paper)</strong></p><!-- テキストはここを編集 -->
    </div>
    <ul class="c-list-disc-a">
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Paper must be produced from forests that are managed in a sustainable manner and the legality of which has been verified.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Paper must not be produced from forests with high conservation value.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Virgin paper/recycled paper must have traceability.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Chemical substances used in production process of paper must be confirmed to be safe.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Environmental and safety management must be under control in the paper manufacturing process (including wastewater and other water management).</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">The paper must be ECF chlorine-free bleached paper.</li>
    </ul>
    <div class="c-text-a" style="max-width: 1360px;">
        <p class="c-text-a__text"><strong>Supplier Standards(Requirements for procurement transactions)</strong></p><!-- テキストはここを編集 -->
    </div>
    <ul class="c-list-disc-a">
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Suppliers must comply with the laws and regulations of the region and country in which they operate, and they must conduct their operations and supply products with consideration for the environment, including climate change prevention, appropriate use of resources, and biodiversity conservation.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Human rights of local residents in the area where the company operates are protected and that the company sustains a good relationship with local residents.</li>
        <li class="c-list-disc-a__item c-list-disc-a__item--black">Human rights of workers and employees are protected and there is no relationship with antisocial forces or groups.</li>
    </ul>
