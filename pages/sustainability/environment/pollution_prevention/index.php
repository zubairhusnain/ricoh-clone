                                <div class="c-h3-a c-h3-a--centera">
  <h3 class="c-h3-a__text">Prevention of contamination at business sites and management of chemical substances contained in products</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">To continuously discuss mid- to long-term issues of the Ricoh Group in the areas of environment, society, and governance at the management level, the ESG Committee, chaired by the CEO, was established in May 2018.
The committee meets once every quarter with the participation of Senior Management to discuss the status of initiatives, issues, and investment decisions related to ESG themes, such as environmental contamination, as important themes for management. Its deliberations are regularly reported to the Board of Directors, which then supervises the execution of ESG activities at a high level.
In addition, we use an environmental impact monitoring system for each fiscal year to oversee our forecasts in comparison to actual results. The global environmental performance data aggregated by the cloud system is analyzed and utilized for PDCA management.</p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a">
  <p class="c-text-a__text">(1) Risk management system for chemical contamination of our business sites<br>
To prevent contamination in and around our business sites due to chemical substances used in manufacturing processes, the Ricoh Group even prohibits the use of hazardous chemical substances that are not listed as a product material in the process of designing and developing products. We also share information within the Ricoh Group and reduce the amount of chemical substances used and emitted into the environment in the phase of actual use.<br>
In addition, we are we are working to minimize the environmental impact of soil contamination caused by past business activities, and when conducting land transactions, we assess the environmental impact caused by chemical substances and promote the necessary management and activities to reduce the environmental impact.</p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a">
  <p class="c-text-a__text">(2) Risk management system for chemical substances used in products<br>
We have established a management system for chemical substances contained in products throughout our supply chain to reduce and control chemical substances that may affect human health and impact the global environment. In addition, by conducting such management, we ensure not only compliance with the laws and regulations of each country in which we operate, but also promote the production of products that meet our own standards, which are stricter than those of environmental labels and other laws and regulations.</p><!-- テキストはここを編集 -->
