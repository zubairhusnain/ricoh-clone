3.Strive to minimize the risk of chemical substances and prevent risks through preventive measures.<br>
4.Contribute to a sustainably growing society by developing and introducing technologies that reduce environmental impact.<br>
5.Consider the possibility of risk trade-offs between human health and environmental safety in activities to improve quality, cost, productivity, etc., and take the necessary measures to address this.<br>
6.Strive to build relationships with society through risk communication build cooperative and trusting relationships.<br>
7.Each employee in the Group strives to continuously improve his/her own abilities and gain knowledge about chemical substances and to share information on chemical substance management necessary in other relevant processes.
