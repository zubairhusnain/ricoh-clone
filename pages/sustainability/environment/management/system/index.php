  <p class="c-text-a__text">
    In order to realize environmental management, it is important if business operations and environmental conservation
    proceed under the same decision-making process, rather than being pursued separately. The Ricoh Group promotes
    sustainable environmental management by incorporating the environmental management system (EMS) as an essential
    process of each business activity. Decisions on the promotion of environmental management and other various
    commitments based on the EMS concept are made by <a href="../../../sdgs/">the ESG Committee</a>, chaired by
    the CEO with oversight, supervision,
    and advice from the Board of Directors. Environmental targets and strategies developed by our top management are
    incorporated into the targets of each organization, and a system has been established to ensure that the results of
    activities are fed back to top management, and a PDCA (Plan-Do-Check-Act) cycle is implemented for the entire group
    and each organization to manage and monitor environmental risks and opportunities. In addition, we operate the
    Sustainable Environmental Management Information System, designed to identify and promote the progress of
    sustainable environmental management. Using this system, we monitor the environmental impact and environmental
    compliance of our entire business activities, utilizing the results for target setting and strategy formulation,
    making decision on environmental management, promoting environmentally-friendly design, improving activities by
    division, training for employees, internal audits, and information disclosure to stakeholders.
  </p>
