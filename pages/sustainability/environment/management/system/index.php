                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Enhancing and Raising the Level of Environmental Management System</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a">
  <p class="c-text-a__text">
    At the Ricoh Group, we have been working to develop and improve environmental management systems (EMS), initially on
    a business site basis, to accelerate our environmental conservation activities. Starting with the Ricoh Gotemba
    Plant, which received ISO/DIS 14001certification in 1995, all major Ricoh production sites worldwide were ISO 14001
    certified by March 2000. Then in 2001, all the group sales subsidiaries in Japan as a whole received ISO 14001
    certification. The overseas sales subsidiaries are also making every effort to acquire ISO 14001 certification. The
    Group has thus promoted the creation of a climate for sustainable environmental management by all employees through
    the acquisition of ISO 14001 certification. (Since February 2007, in an effort to fuse business and environment and
    pursue environmental management, our business site-based EMS worldwide were revised to become business
    division-based, placing business activities and environmental protection activities under a single decision-making
    process. In tandem with this initiative, Ricoh and its sales subsidiaries in Japan have acquired integrated ISO
    14001
    certification. Moreover, in December 2013 accreditation was completely integrated within Japan, governance was
    strengthened while at the same time a rationalization of accreditation business was conducted.) Since February 2007,
    we changed to an EMS that incorporates environmental risks and opportunities into the processes of each business
    activity to integrate business and environmental management, and to promote business and environmental conservation
    activities under the same decision-making process. In December 2013, we integrated all domestic certifications to
    strengthen governance and improve the efficiency of certification operations.
  </p>
  <p class="c-text-a__text">
    * For the status of the Ricoh Group’s ISO 14001 acquisition, please visit “<a href="../iso/">Ricoh Group’s ISO 14001</a>”
