                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Participatory Approach by All Employees</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a">
  <p class="c-text-a__text">
    At Ricoh, we are making efforts to improve sustainable environmental management based on the “All Employee
    Participation Approach”. This “All Employee Participatory Approach” means that all employees in all divisions—such
    as R&amp;D, product design, procurement, manufacturing, logistics, sales, maintenance/services and collection and
    recycling—participate in environmental activities through incorporating an environmental perspective.
  </p>
  <p class="c-text-a__text">
    These activities are regarded as just as important as “QCD activities,”* which involve pursuing profitability. To
    improve environmental activities, internal benchmarks and know-how are provided to all employees from time to time
    to
    make them more environmentally aware. For example, the rules that each and every employee must follow in all
    processes,
    including due diligence, compliance with environmental laws and regulations, and training plans, are incorporated
    into
    the Ricoh Group Standards (RGS), which are linked to our daily activities.
  </p>
  <p class="c-text-a__text">
    The Ricoh Group’s basic policy for environmental management is to simultaneously reduce environmental impact and
    generate profits. The foundation of the Ricoh Group’s environmental management is for each employee to be aware of
    how his or her activities affect the environment.
  </p>
  <p class="c-text-a__note">
    *QCD activities improve the management of Quality, Cost, and Delivery.
  </p>
