      Ricoh has been organizing the environmental event "Global Eco Action" every June since 2006 to encourage
      reflection and action on global environmental issues. In 2019, "Global Eco Action was renamed "Ricoh Global SDGs
      Action," focusing not only on eco-actions such as measures against global warming towards achieving a decarbonized
      society, but also on addressing a wide range of social issues collectively by group employees.
