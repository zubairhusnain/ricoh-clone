  <section class="c-h4-a">
    <h4 class="c-h4-a__text">
      2.SDGs Online program
    </h4>
    <p class="c-text-a__text">
      We have developed the SDGs online program focusing on themes deemed crucial in the fields of environment, society,
      governance, and social contribution. Environmental themes include achieving a decarbonized society and promoting a
      circular economy. These courses consist of approximately 10-minute lectures provided through video content,
      designed
      to be accessible during spare moments, with knowledge retention ensured through assessment tests. They are stored
      on
      an ESG education site accessible to all employees to ensure a correct understanding of ESG/SDGs.
    </p>
  </section>
  <section class="c-h4-a">
    <h4 class="c-h4-a__text">
      3.Evaluation Activities and Environmental Education in Production Areas
    </h4>
    <p class="c-text-a__text">
      Ricoh Group promotes "Ricoh Way" practices specifically in production areas. As a foundation for manufacturing, it
      has established 12 fundamentals including environmentally friendly production activities, implemented in
      production
      facilities both domestically and internationally. One notable feature is the participation of all employees.
      Beyond
      global awareness, each production facility's adherence to these principles is evaluated, incorporating employee
      interviews based on specific criteria. Facilities with lower evaluations learn from those with higher evaluations,
      leading to overall improvement in implementation across all production sites. To enhance environmental practices,
      Ricoh Group has created booklets and practical manuals incorporating good practices in environmental management
      (such
      as energy consumption reduction), circular economy (resource efficiency, waste reduction), efficient water use
      (water
      conservation), pollution prevention policies, goals, and exemplary practices in production sites. These
      educational
      materials are provided to domestic and international production facilities, accompanied by comprehension tests for
      all employees at targeted production sites* (FY2023 implementation rate: 100%). With the evolution of Ricoh
      Group's
      environmental management, these booklets and manuals are periodically revised.
    </p>
    <p class="c-text-a__note">
      <sup>*</sup>Targeted production sites: 19 production sites for main products (MFPs, printers, scanners,
      commercial/industrial printings, digital cameras, embedded computers, etc.)
