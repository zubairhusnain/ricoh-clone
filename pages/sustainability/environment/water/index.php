                                <div class="c-text-a">
  <p class="c-text-a__text">To continuously discuss mid- to long-term issues of the Ricoh Group in the areas of environment, society, and governance at the management level, the ESG Committee, chaired by the CEO, was established in May 2018. The committee meets once every quarter with the participation of Senior Management to discuss the status of initiatives, issues, and investment decisions related to environmental issues, including water risks, as important themes for management. Its deliberations are regularly reported to the Board of Directors, which then supervises the execution of ESG activities at a high level.<br><br>

In addition, the Group has established a water resource management structure at each business site to control wastewater discharge and water intake.
</p><!-- テキストはここを編集 -->
</div>

<div class="c-h3-a">
        <h3 class="c-h3-a__text">Collating data and formulating water management plans​</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group formulates water management plans for its approximately 300 global sites, including major production sites, based on the amounts of water used, discharged, and recycled, and manages the plans and results for each fiscal year. The Ricoh Group's environmental impact monitoring system analyzes data on water intake and wastewater discharge and utilizes this data for PDCA management.</p><!-- テキストはここを編集 -->
</div>

<div class="c-h3-a">
        <h3 class="c-h3-a__text">Water risk assessment and response to water stress regions​</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">We utilize the "Aqueduct Water Risk Atlas" from the World Resources Institute (WRI) to assess water stress and water scarcity risks at our production sites and conduct water risk assessments. Among the indicators set in "Aqueduct Water Risk Atlas 4.0," business sites categorized as "high" or above in "Baseline Water Stress" or "Baseline water depletion" are identified as "water stress areas." As a result of the evaluation, it has been confirmed that the withdrawal rate from water stress areas accounts for less than 10% of Ricoh Group's total water intake, and sites located in water stress areas comprise less than 10% of all Ricoh Group business sites. The water stress areas in which we operate include seven locations: China, Thailand, Indonesia, the US and France with a total water intake of 274,586㎥ for fiscal year 2024. As part of measures in water stress areas, we actively engage in dialogue with stakeholders such as local administrations and communities. For example, we set voluntary targets significantly below the water intake restriction limits imposed by authorities and have achieved initiatives towards meeting these targets.</p><!-- テキストはここを編集 -->
</div>
