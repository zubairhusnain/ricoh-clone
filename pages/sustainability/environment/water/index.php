    </div>
    <div class="c-text-a" style="max-width: 1360px; margin-top: 0px;">
        <p class="c-text-a__text">1.We will act based on the recognition that access to safe and secure water resources is the right for all people.<br>
        2.We will act by setting targets, considering the impact of our business activities on water resources as well as regional characteristics.<br>
      3.We will manage water resources in compliance with laws and regulations as well as international standards, initiatives, and public policies.<br>
4.We will contribute to solving water resource issues not only within our own company but also in society through our technological innovations.<br>
5.We will strive to improve the awareness of all employees, with each taking the initiative in communicating with stakeholders to help solve water resource issues in local communities.<br>
6.We will consider not only resource conservation but also climate change and pollution prevention when procuring raw materials, products and services, and the equipment we use.
</p><!-- テキストはここを編集 -->
