<div class="c-text-a">
  <p class="c-text-a__text">
    Our mission &amp; vision endorse the Ricoh founding principles embodied in The Spirit of Three Loves —Love your
    neighbor, Love your country, Love your work—through which we empower individuals to find fulfillment through work by
    understanding and transforming how they work, so they can unleash their potential and creativity to realize a
    sustainable future. Under this mission, we set the six materiality issues, Creativity from Work, Safe and secure
    digital society, Fair corporate activities, Inclusive workforce, Coexistence with communities, Zero-carbon society
    and circular economy.
  </p>
  <p class="c-text-a__text">
    Our social contribution activities are also aligned with our management policy and SDGs and we set Priority Areas
    based on our Materiality and global demand. Our Priority Areas are 1) Inclusion in the Workplace, 2) Community and
    Social Development, and 3) Response to Climate Crisis and Biodiversity. To maximize the effects of our contributions
    toward solving challenges, we have also set fundamental principles on social contribution. Under these principles,
    Group companies are implementing measures by leveraging the Group’s strengths, including human and other resources.
  </p>
