<div class="c-h3-a">
  <h3 class="c-h3-a__text">To join the Responsible Business Alliance (RBA)</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">
    In November 2019, Ricoh joined the Responsible Business Alliance (RBA), the world’s largest industry coalition
    dedicated to promoting corporate social responsibility in global supply chains. Ricoh shares the principals and
    goals of the RBA and has committed to adopting and implementing the measures initiated by the RBA, and also sharing
    them with our suppliers.<br>
    Furthermore, we are utilizing the RBA-Online platform, which is the platform of the RBA, to receive various data
    from our suppliers regarding their initiatives on environmental, social, and governance (ESG) practices. We use
    RBA's management indicators as benchmarks to collaborate with our suppliers in addressing and reducing ESG risks,
    with the aim of promoting sustainable business activities. Our suppliers actively participate by exchanging
    information on initiatives such as hosting ESG briefing, implementing power reduction programs to promote
    decarbonization, and various other efforts. Additionally, Ricoh provides support by actively advising and assisting
    in these initiatives.
  </p>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">In accordance with RBA's certification program, our global production sites have adopted
    take RBA's Self-Assessment Questionnaire (SAQ) and the Validated Assessment Program (VAP), a formal third-party
    audit. The VAP also evaluates the number of suppliers and the number of assessments conducted, the number and
    progress of high-risk supplier improvements, and the number and status of companies implementing improvement support
    programs.</p>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">In previous audits, there have been no instances of non-compliance evaluations regarding the
    quantitative data submitted to the auditing agency. Among the three certification ranks available
    (Platinum/Gold/Silver), all audited locations have obtained either Gold/Silver certification.</p>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">For a list of certified production facilities, please refer to the Human Rights page.</p>
</div>



