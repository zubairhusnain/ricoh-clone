<div class="c-h4-a">
  <h4 class="c-h4-a__text">Survey conducted in fiscal 2024 and future efforts</h4>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">In fiscal 2024, based on the results of a survey conducted for worldwide first-tier suppliers of the Ricoh Group , we identified as accurately as possible each of the parts and raw materials used in the products manufactured or consigned during the year, and conducted a common survey on the use of conflict minerals and received CMRT responses from 98% of suppliers. In the survey of 2024, the Ricoh Group identified 210 smelter companies that have acquired the certification of RMAP Conformant and are conflict-free. The rate of RMAP Conformant smelters in the total number of identified smelters and refineries in the Ricoh Group supply chain was 62% in fiscal 2024. The rate of smelters with RMAP certification / active smelters was 63% in fiscal 2024. In recent years, as the number of companies surveyed has increased, the number of newly specified smelters and refineries that have not obtained RMAP Conformant has been increasing, while the number of RMAP Conformant smelters has been excluded from RMI certified smelter list. As a result, the ratio of RMAP Conformant smelters has been temporarily decreasing. Therefore, we will continue to call on Tier 1 suppliers to switch to RMAP Conformant smelters. We also expect tier 2 and subsequent suppliers to encourage upstream companies and smelters to switch to RMAP Conformant smelters.<br>Starting with the fiscal 2021 survey, we requested suppliers to report the scope of their CMRT/EMRT responses not on a company basis (A: Company) but on a part-by-product basis (B: Product) delivered to Ricoh Group. As a result, about 90% of suppliers responded to the questionnaire on a part-by-product basis.</p>
