<div class="c-h3-a">
  <h3 class="c-h3-a__text">Ricoh Group Supplier and Partner Code of Conduct</h3>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">In January 2006, the Ricoh Group established the Ricoh Group Supplier Code of Conduct for
    our suppliers to help them understand and support the Ricoh Group’s basic ESG policy and promote efforts aimed at
    improving society and the global environment as well as the sustainable development of businesses. The code of
    conduct is distributed to all our suppliers, who are required to comply with it. In August 2020, the Ricoh Group
    revised the "Supplier Code of Conduct" complying with the RBA Code of Conduct, which is based on major international
    human rights standards, including the ILO Declaration on Fundamental Principles and Rights at Work and the Universal
    Declaration of Human Rights in line with the UN Guiding Principles on Business and Human Rights. In April 2023, we
    revised the code to the "Ricoh Group Supplier and Partner Code of Conduct" as a code of conduct to be applicable to
    business partners in addition to suppliers of the Ricoh Group. For suppliers and business partners implementing the
    Supplier and Partner Code of Conduct, the working environment is safe, and the workers are treated with respect and
    dignity. We would also like our suppliers and partners to ethically work on this revised Code of Conduct for
    conducting business and, at the same time, to be environmentally responsible. If any conduct contrary to this Code
    occurs, the Ricoh Group may suspend transactions depending on the seriousness of the situation.</p>
</div>

