  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text u-fz-14"><sup>*1</sup> RBA: Responsible Business Alliance, organizations promoting ESG in
      supply chain. Ricoh as a member of the RBA, is engaged in activities to promote ESG throughout the supply chain.
    </p>
  </div>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Ricoh Group basic policy in procurement activities</h3>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">The Ricoh Group’s businesses are supported by many suppliers. Recognizing these suppliers
      as our essential business partners, we build a relationship of trust with them, aiming at mutually beneficial
      development.<br>
      Today’s society faces various issues to address, such as those associated with the environment and human rights.
      To help solve these issues and achieve a sustainable society, the Ricoh Group promotes business activities so as
      to achieve SDGs, upholding the slogan of “Driving Sustainability for Our Future.” In order to effectively pursue
      this goal to meet social expectations, we need to cooperate with the entire supply chain, sharing our group
      policies and visions with individual suppliers. To this end, we have established the Ricoh Group purchasing
      regulation to appropriately deal with relevant ESG issues involving legal compliance, fairness and environmental
      and societal impacts. Using this as a tool, we are working to enhance our efforts on a global scale.</p>
  </div>
</div>

<div class="c-h4-a">
  <h4 class="c-h4-a__text">Ricoh Group Purchasing Regulation</h4>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>[Fairness of Dealing]</strong><br>
      To operate the purchase activities in impartial and fair manner which is open to all over the world, based on the
      economic rationality.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>[Environmental Conservation]</strong><br>
      To operate, as a member of the global citizen, the purchase activities in such a manner as to contribute to the
      conservancy and the improvement of the global environment.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>[CSR]</strong><br>
      To operate the purchase activities bearing in mind CSR and based on the compliance with law and esteem of the
      social ethics.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>[Coexistence &amp; Co-prosperity with Suppliers]</strong><br>
      To aim at coexistence and co-prosperity with excellent Suppliers on the basis of mutual responsibility.</p>
  </div>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Structures</h3>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">To continuously discuss mid- to long-term issues of the Ricoh Group in the areas of
      environment, society, and governance at the management level, the ESG Committee, chaired by the CEO, was
      established in May 2018. The Board of Directors discusses policies, directions, and long-term goals related to
      sustainability, including supply chain management, and incorporates the decisions into the ESG Committee, which
      supervises activities to ensure their implementation. In December 2021, we established a department to oversee
      ESG-related procurement and purchasing. The headquarters purchasing department, under the supervision of the
      supply chain function manager who is a member of the ESG Committee, is responsible for appropriately managing
      supply chain risks within the Ricoh Group. </p>
  </div>
</div>

