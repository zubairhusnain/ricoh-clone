                        <h2 class="c-h2-a__text">Building relationship with suppliers based on trust</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">We work to forge relationships of strong trust and long-term cooperation with our
      suppliers, aiming at mutually beneficial development. We do this by providing:</p>
  </div>
</div>

<ul class="c-list-disc-a">
  <li class="c-list-disc-a__item c-list-disc-a__item--black">The Ricoh Group Supplier and Partner Code of Conduct</li>
  <li class="c-list-disc-a__item c-list-disc-a__item--black">Production trend briefings</li>
  <li class="c-list-disc-a__item c-list-disc-a__item--black">ESG briefing for suppliers<br>We provide education and
    training to our suppliers through the ESG briefing. We started by explaining basic matters such as Ricoh's
    initiatives and the Supplier and Partner Code of Conduct, and now we are explaining more advanced matters such as
    setting decarbonization targets, conducting ESG audits, and implementing improvement programs for suppliers that we
    have identified as high risk. Since 2020, for the purpose of preventing the spread of Covid-19, we have held
    online-briefings for the first time with our main global suppliers.
  </li>
  <li class="c-list-disc-a__item c-list-disc-a__item--black">Supplier and Partner Hotline</li>
</ul>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">We have also established a network infrastructure called "RaVenderNET" to operate with our
      suppliers, which is utilized not only for exchanging production information and data on the environmental impact
      of raw materials and components but also for sharing information related to ESG procurement.</p>
  </div>
