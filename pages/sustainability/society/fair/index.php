                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Addressing the conflict minerals issues</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">With regard to the responsible supply chain management of minerals from conflict-affected areas and high-risk areas(CAHRAs) like the Democratic Republic of the Congo (DRC) and the adjoining countries, in order that companies respect human rights and avoid contributing to conflict through their mineral sourcing practices, it is expected to cultivate transparent mineral supply chains and companies’ sustainable growth by the righteous decision-making on the mineral resource procurement with a view to enabling countries to benefit from their natural mineral resources and preventing the extraction and trade of minerals from becoming a source of conflict, human rights abuses, and insecurity.</p>
  </div>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Ricoh Group’s Responsible Minerals Procurement Policy</h3>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">The Ricoh Group established “Ricoh Group’s Responsible Minerals Procurement Policy” in 2022 to secure transparency in the supply chain with its business partners and ensure responsible mineral sourcing practices because mineral mining or trading in conflict-affected and high-risk areas finances armed groups and fosters conflicts. These activities are also closely related to human rights abuses, labor and important social issues, and other problems such as environmental destruction. As part of our efforts to eliminate the use of potentially conflict minerals, we are calling for the identification and elimination of products sourced from supply chains that include high-risk smelters.</p>
  </div>
</div>

<a href="/ricoh-clone/ricoh_offline/assets/www.ricoh.com/-/Media/Ricoh/Sites/com/csr/fair/pdf/Ricoh-Groups-Responsible-Minerals-Procurement-Policy-ENG.pdf/" class="c-link-a c-link-a--pdf icon-hidden">
