<div class="c-h3-a">
  <h3 class="c-h3-a__text">Efforts to Ensure Proper Management of Transactions and Payments</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">For transactions involving direct materials within the Ricoh Group in Japan, we mutually
    confirm the payment terms before the transactions take place. In accordance with the relevant laws and regulations,
    we issue
    written documents stating the payment terms and other relevant details to applicable business partners. Information
    from the acceptance inspection is automatically linked to our accounting system, enabling payment processing based
    on the agreed terms. We also issue a “Payment Notice” that specifies the payment amount, payment date, and an
    itemized statement.<br>
    For transactions involving indirect materials—particularly auxiliary materials—we are promoting the use of an
    integrated management system that covers the entire process from quotation and ordering to the acceptance
    inspection. To ensure payments are made according to the agreed terms, the system includes functions for prompting
    payment processing and a mechanism that prevents any changes to the order amount by the Ricoh Group after the order
    has been placed.</p>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Supplier and Partner Hotline</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Ricoh has set “Supplier and Partner Hotline” which accepts violations to the applicable laws
    and regulations, Ricoh Group Code of Conduct, and violations of contract with supplier and Partner caused by Ricoh
    and Ricoh Group’s officers and employees. There was one report in fiscal 2022, but it has been resolved, and there
    were no reports in fiscal 2023 and 2024.</p>
</div>

<div class="c-h4-a">
  <h4 class="c-h4-a__text">(1) The reports we accept on “Supplier and Partner Hotline”</h4>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">The conduct of officers and employees of each Ricoh Group company is governed by laws and
    regulations, Ricoh Group Code of Conduct.<br>If you find that officers and employees of the Ricoh Group has (or may
    have) breached any of the above rules, laws or regulations, or any contract with you as a Supplier and Partner,
    please contact Supplier and Partner and Partner Hotline with the details.
    In addition, please refrain from reporting with improper purposes, such as reporting contents that are different
    from the facts, reporting contents for purposes of slander, intimidation or business.</p>
</div>

<div class="c-h4-a">
  <h4 class="c-h4-a__text">(2) How to report to Supplier and Partner Hotline</h4>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Reports to Supplier and Partner Hotline are accepted through the report form on this
    site.(See below)As a general rule, please report under your real name. Anonymous reports are also accepted, but in
    that case, there is a limit to the confirmation of the facts, etc., and there is a possibility that sufficient
    investigation may not be conducted.<br>In addition, please note that we cannot contact you about the results of the
    response, etc.</p>
</div>

<div class="c-h4-a">
  <h4 class="c-h4-a__text">(3) Response to the reports</h4>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Reports to Supplier and Partner Hotline are received and the relevant facts are confirmed by
    the department not in charge of Ricoh’s normal procurement. We conduct corrective actions promptly when necessary.
    The whistleblower shall not receive disadvantageous treatment by Ricoh Group merely by submitting the report itself.
  </p>
</div>

