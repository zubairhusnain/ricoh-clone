                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Policy and Basic Concept</h2>
                    </div>
                    <div class="c-text-a">
        <div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">Our business activities give us a large sphere of influence when it comes to social
      accountability, so it is crucial for the many companies and individuals along our supply chain to help the Ricoh
      Group avoid or minimize unintended negative effects. We are a member of the RBA<sup>*1</sup> (Responsible Business
      Alliance), a global industry coalition dedicated to progressing social responsibility in global supply chains and
      we make sure not only our employees, but also the employees of our suppliers, always act ethically. We spotlight
      this concern in our international guidelines on human rights, labor, the environment and more, and are working
      continuously to raise our initiatives to the next level.</p>
  </div>
</div>

<div class="c-figure">
  <div class="c-figure__inner">
    <div class="c-figure__item">
