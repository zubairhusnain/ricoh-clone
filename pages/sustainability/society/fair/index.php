<div class="c-h3-a">
  <h3 class="c-h3-a__text">Conducting Conflict Minerals Survey</h3>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">Ricoh Group is working to improve the transparency of its due diligence by addressing conflict minerals issues referring to the “OECD Due Diligence Guidance for Responsible Supply Chains of Minerals from Conflict-Affected and High-Risk Areas". We ask our suppliers to use the CMRT (Conflict Minerals Reporting Template) and EMRT (Extended Minerals Reporting Template ) formats provided by RMI (Responsible Minerals Initiative) <sup>*3</sup>. Since 2013, Ricoh Group has conducted an annual Conflict Minerals Survey of suppliers of raw materials and parts used in its products. Our goal is to achieve 100% response rate from suppliers and 100% product-based response in the Conflict Minerals Survey by FY2025.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>Step1: Establish strong company management systems</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">In 2012 the Ricoh Group started an in-house study system to approach conflict minerals issues, and we established a cross functional task force in charge of dealing with conflict minerals issues. The task force, which consists of representatives from relevant departments within Ricoh Group companies, began considering what actions to be taken for the issues. We are continuing these activities, led by the Procurement Division and the ESG Division. Each year we plan and carry out an annual Conflict Minerals Survey. From fiscal 2021, in line with the survey policy of “Achievement of conflict-free sourcing”, we have been started to centrally managing the Conflict Minerals Survey data to improve with the aim of improving the efficiency of collecting responses to this survey. In fiscal 2022, we established the “Ricoh Group’s Responsible Minerals Procurement Policy” and since then we have asked our suppliers to cooperate with the Ricoh Group Conflict Minerals Survey.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>〔Education and training on conflict minerals issues〕</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">At the ESG briefing for suppliers, we address the issue of conflict minerals as one of the themes to ensure that suppliers are provided with information and educational opportunities. In addition, in conjunction with the annual Conflict Minerals Survey, Ricoh Group provides education on the latest legal amendments and other trends related to responsible mineral procurement and Ricoh Group's Conflict Minerals Survey activities to purchasing and procurement personnel at all Ricoh Group global sites. We also produce videos introducing the significance of the Conflict Minerals Survey and Ricoh Group's initiatives on conflict minerals for all Ricoh Group companies and employees to raise awareness.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>Step2: Identify and assess risks in the supply chain</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">From 2013, we have been conducting a yearly conflict minerals survey targeting suppliers of raw materials and components to be used for the Ricoh Group’s products. Until fiscal 2020, we surveyed suppliers of major products such as imaging products. From fiscal 2021, we expanded the scope of our survey to include all products that Ricoh is responsible for producing and selling and asked our suppliers to limit the scope of the survey to those parts and products that Ricoh Group delivers. In addition, considering the growing concerns about unsafe working environments and child labor in recent years in the mining of cobalt, we have been conducting surveys of the supply chain of cobalt since fiscal 2020. We ask suppliers to use the Conflict Minerals Reporting Template (CMRT) and the ,Extended Minerals Reporting Template(EMRT) which provides conflict minerals reporting formats provided by RMI*3.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>Step3: Design and implement a strategy to respond to identified risks</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">From fiscal 2020, we provide information on high-risk smelters to our tier 1 suppliers and encouraging them to switch to RMAP (Responsible Minerals Assurance Process) Conformant smelters. We also ask tier 2 and subsequent suppliers to encourage upstream companies and smelters to switch to RMAP Conformant smelters and obtain certification through tier 1. As a result of the analysis of response information, we are calling on suppliers who indirectly procure from high-risk smelters to switch smelters directly through documents.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>Step4: Carry out independent third-party audit of smelter/refiner’s due diligence practices</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">Ricoh, as a member company of the "Responsible Minerals Trade Working Group", launched in May 2012 by JEITA<sup>*4</sup>, is participating in a Working Group for the entire global supply chain, and studying activities unified in the electronics industry. In 2019, the Ricoh Group participated in the RBA (Responsible Business Alliance) and member companies of RMI, to ask the conflict minerals smelters related organizations in Japan to make inquiries about smelters and promote to be the RMAP Conformant continuously.</p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text"><strong>Step5: Report annually on supply chain due diligence</strong></p>
  </div>
</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">Ricoh's activities related to conflict minerals are published annually on its website and in the Integrated Report. We have identified that our toner are conflict-free.</p>
