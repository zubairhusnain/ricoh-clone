<div class="c-h3-a">
  <h3 class="c-h3-a__text">Holding a Briefing Session on Procurement Policy</h3>
</div>

<div class="u-dsp-f u-fl-dire-col">
  <div class="c-text-a u-w-100p u-mr-16 u-sp-mr-0">
    <div class="c-text-a">
      <p class="c-text-a__text u-fz-14">
        We host procurement briefing sessions for major suppliers to explain our procurement policy as well as to boost
        their understanding of the Ricoh Group’s ESG policy. The Ricoh Group's day-to-day stable production activities
        are the result of the cooperation of our suppliers, and we consider that the briefing sessions are opportunities
        to build further win-win relationships. In 2019, we held procurement briefing sessions in China (Shanghai and
        Shenzhen) and Thailand (Bangkok).<br>
        We also hold CSR seminars (renamed ESG briefing in fiscal 2021) for suppliers to engage in ESG activities in
        tune with the entire supply chain. Since fiscal 2020, we have been holding events in a hybrid format, combining
        online and in-person components, due to the impact of Covid-19. We share information with our suppliers on
        social topics such as global environmental issues, the significance of the SDGs, and policies and targets of the
        Ricoh Group. In addition, we implement SAQ based on the RBA Code of Conduct and confirm the situation of ethics,
        environment, human rights, labor, safety, and health, etc. In feedback, we show their compliance level of the
        codes, suggesting not only items for improvement, but also highlighting specific areas in which they excel, and
        we try to
        communicate interactively. We also work in tandem with high-risk suppliers to help them improve their
        management. Together with the supplier's management and employees, improvement measures are developed and
        implemented, and follow-up audits are even conducted to check the situation afterwards.
