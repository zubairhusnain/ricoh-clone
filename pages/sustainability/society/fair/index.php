<div class="c-h3-a">
  <h3 class="c-h3-a__text">Supply chain BCM (business continuity management)</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group’s extensive supply chain faces a broad range of external risk factors, such as natural disasters, changes in the international situation, and development of infection. Our customers are particularly aware of this in the wake of the Great East Japan Earthquake. They are demanding, as part of their business requirements, strong risk management capabilities to ensure that their business operations would not be affected even in the event of an emergency. The Ricoh Group's policy is to ensure that customers never have to suspend their work, and we have made our support of social infrastructure operations a high priority. We, therefore, require our suppliers to strengthen their BCM by maintaining redundant production bases and parts procurement channels, and to increase their stocks of materials and components in case of widespread disasters such as those caused by earthquakes, tsunami, floods, fire, accidents or infection including new strains of influenza and COVID-19.</p>
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Identifying risks associated with suppliers</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">We assess risks associated with each supplier in consideration of its location of operation and the possibility of involving environmentally hazardous substances. Based on the assessment, we identify high-risk suppliers and carry out measures to reduce the risk through periodically monitoring the financial situation, introducing the SAQ programs and providing for third-party audits. We also conduct annual compliance risk screening for all suppliers in accordance with our anti-corruption and anti-bribery policy.
In fiscal 2018, we conducted two unannounced audits of suppliers with coating processes suspected of containing or contaminated by prohibited substances. Thorough the inspection of their production sites, we confirmed that all products were lead-free electroless nickel-coated and determined that there was no possibility of the inclusion of prohibited substances.</p>
</div>

