<div class="c-h4-a">
  <h4 class="c-h4-a__text">SAQ System</h4>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">We have introduced a SAQ System based on the RBA Code of Conduct that helps suppliers monitor their compliance with the Ricoh Group Supplier and Partner Code of Conduct. The system has been rolled out domestic and overseas production sites. Company activities are assessed in labor, safety and health, environment, ethics, management systems, and living wages to identify issues to address. The results are fed back to the suppliers, who receive requests for improvement if applicable, together with corrective action plan, advice, and support on ways to meet society's needs and expectations. If a supplier's improvement activities are not sufficient, we would discuss the future business relationship with the supplier. With the SAQ System, the Ricoh Group provides our suppliers with support in implementing a "plan, do, check, act" (PDCA) cycle by themselves to meet society’s needs and expectations. In addition to providing individual feedback to each supplier on their SAQ responses, we also send charts showing the average results for each supplier category.</p>
