</div>

<div class="c-text-a">
  <div class="c-text-a">
    <p class="c-text-a__text">As a result, analyzing the response information from the first-tier suppliers, it was confirmed that there was a possibility that a certain number of products contain parts or materials which originated in the Democratic Republic of the Congo or an adjoining country. Accordingly, the Ricoh Group conducted due diligence on the relevant first-tier suppliers. We will discuss our future business with the suppliers who have not responded to this survey and are judged to require improvement based on the results of the ESG Self-Assessment.<br>In addition, in fiscal 2020, we began a survey of the cobalt supply chain by identifying major suppliers that had supplied the Ricoh Group with products and parts containing cobalt in the past. With a 98% response rate from suppliers in the 2024 survey, the number of identified cobalt smelters and refineries was 80, of which 43 were RMAP Conformant smelters. We also continue to cooperate with industry organizations, such as JEITA and RMI, and we continue to conduct due diligence.</p>
