          executives and employees, with top management sharing information concerning the current state of the company
          and their management policies with representatives from all offices.
        </p>
        <p class="c-text-a__text">
          The information is subsequently conveyed to all employees through workplace meetings as well as through the
          Council’s newsletters. In addition, issues requiring top management consultation, such as pay raises, bonus
