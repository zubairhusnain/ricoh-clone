    Freedom of Association
  </h3>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">
    In Ricoh Group’s Human Rights Policy, we stipulate respect for the basic rights of employees as indicated in the
    International Bill of Human Rights and the International Labour Organization (ILO) Declaration on Fundamental
    Principles and Rights at Work.
  </p>
  <p class="c-text-a__text">
    Ricoh Group has the Human Rights Violation Prevention Standard, which stipulates that corporate activities and human
    rights taken into consideration in daily business activities. At the Standard, “Freedom of association” is specified
    as one of the important elements in respecting human rights. Each company has a place for dialogue with employees
    according to the circumstances of the country or region. At Ricoh, from the founding spirit, we have an Employee
    Council in which all employees and executives are members.
  </p>
  <p class="c-text-a__text">
    Employee Council has established with the aim of mutual communication between labor and management and collaborate
    under the basis of common values of business goals.
  </p>
