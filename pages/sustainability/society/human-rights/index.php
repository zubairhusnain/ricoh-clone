  <h3 class="c-h3-a__text">Corrective or disciplinary action taken in case of discriminatory behavior or harassment</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">In the event that a violation of human rights or harassment is confirmed, the Ricoh Group places the highest priority on restoring the victim's ability to work safely and securely with zero tolerance policy, while appropriately punishing the perpetrator (including the perpetrator's supervisor in some cases) and providing guidanceappropriate to the severity of the offence. For malicious acts, the perpetrator is subject to disciplinary action in accordance with the work rules and Group standards for human rights violations established by each company, and the perpetrator is warned so that similar acts will never occur again, and management and supervision by superiors are strengthened. In addition, after giving utmost consideration to the privacy of both the victim and the perpetrator, the case is shared with management and managers in the area where the incident occurred, and management checks are conducted to ensure that similar violations do not occur in other organizations.</p><!-- テキストはここを編集 -->
</div>

<div class="c-h3-a">
  <h3 class="c-h3-a__text">Initiatives to Protect Workers' Human Rights</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Based on our human rights policy, we will strive to provide a work environment where the human rights of all workers within the Ricoh Group and in the Ricoh supply chain are respected.</p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a">
  <p class="c-text-a__text"><strong>Respect for freedom of association and the right to collective bargaining</strong><br><br>
We respect the freedom of association and the right to collective bargaining In accordance with the laws of each country, and we respect the rights of workers to form and join labor unions, to bargain collectively, and to participate in peaceful assemblies. We also respect the rights of workers who do not participate in labor unions and shall openly communicate and share their opinions and concerns regarding working conditions and management practices with management without fear of discrimination, intimidation, harassment, retaliation, or unfair treatment. ​<br>
As of the end of fiscal 2024, the unionization rate at the two Ricoh Group companies in Japan with labor unions stood at 69.5%. ​
  </p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a">
  <p class="c-text-a__text"><strong>Prevention of Forced Labor</strong><br><br>
    We will verify personal identification documents to the extent necessary for employment and will not retain original documents except as necessary to comply with local laws and regulations.<br>
    In addition, we do not impose unreasonable restrictions on access to facilities provided by the company, including dormitories, nor do we restrict workers' freedom of movement outside of work periods or during breaks.<br>
    We pay workers regularly, in full, and on time, and issue pay slips that clearly state any legitimate deductions.<br>
	The terms and conditions of employment are clearly explained in a language the worker can understand before employment begins, and employment commences only after mutual agreement has been reached.
  </p><!-- テキストはここを編集 -->
</div>

<div class="c-text-a">
  <p class="c-text-a__text"><strong>Initiatives to Address Harassment from Customers</strong><br><br>
    When employees are subjected to acts that constitute customer harassment, we respond firmly in accordance with the Ricoh Group Basic Policy on Customer Harassment Response in Japan to protect each employee and respect human rights.
  </p><!-- テキストはここを編集 -->
  <p class="c-text-a__text">After establishing this policy, we conducted awareness and educational activities for employees during Human Rights Week. Furthermore, in business units with frequent customer interactions, we defined specific reporting routes and developed a system to ensure prompt and appropriate responses.</p>
</div>

