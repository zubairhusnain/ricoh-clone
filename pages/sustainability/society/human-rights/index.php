                        <h2 class="c-h2-a__text">Structures and Systems</h2>
                    </div>
                <div class="c-text-a" style="max-width: 100%;">
  	<p class="c-text-a__text">The Ricoh Group’s efforts to respect human rights are promoted mainly by the Human Resource Division and ESG Division, under the responsibility of the executive officer in charge of Human Resources and the executive officer in charge of ESG, in cooperation with the Procurement and Risk Management Divisions. Issues related to the respect for human rights(＊), such as the mitigation and corrective measures to the salient human rights issues identified in the human rights impact assessment, are reported by the ESG Strategy Division, which is the promotion department, to the ESG Committee for discussion. The issues that require discussion by the Board of Directors will be presented to the Board.<br>
		Human rights risks are positioned as one of the material management risks and are managed within the Ricoh Group's risk management system. Progress is reported to the Group Management Committee (GMC) once every six months.<br>
		In 2021, we established human rights risk management key roles within all Ricoh business units, and in 2024, we set up key roles in major domestic and overseas group companies. Human rights risks related to business promotion are shared among the persons in these key roles, and we have set up a system to manage and respond to these risks in cooperation with the Group headquarters.
	</p><!-- テキストはここを編集 -->
