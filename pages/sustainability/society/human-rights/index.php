    the relevance of identified risks and stakeholders. In 2022, in response to the increasingly complex human rights
    issues in recent years, we identified major human rights risks in the Ricoh Group and sorted out their impact on
    stakeholders, referring to major international human rights rules and frameworks, as well as the "Major Human
    Rights Risks Related to Enterprises' Consideration and Corporate Activities" defined by the Ministry of Justice in
