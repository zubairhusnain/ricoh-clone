                        <h2 class="c-h2-a__text">Policy and Basic Concept (Ricoh Group’s Human Rights Policy)</h2>
                    </div>
                <div class="c-text-a" style="max-width: 100%;">
  <p class="c-text-a__text">Human rights are fundamental rights that all people are entitled to, and the extent of that entitlement should be extremely deep and wide. The concept of human rights is now a fundamental international social issue that must be addressed by all companies wherever they operate. The global community expects companies to operate with due respect for the human rights of all people based on this basic concept.<br>
    The origin of Ricoh Group’s respect for human rights lies in one of the Founding Principles —“Love your neighbor”— of our corporate philosophy, which is known as “the Spirit of Three Loves”. Not only do we meet all the regulatory requirements and social expectations in the countries and regions in which we operate, but we also demonstrate our commitment to human rights by following international standards such as the “International Bill of Human Rights” and the “ILO Declaration on Fundamental Principles and Rights at Work”. Furthermore, as a signatory to the United Nations Global Compact, we support “The Ten Principles of the United Nations Global Compact”. We firmly believe that we enhance our corporate value by respecting the human rights of all people involved in the Ricoh Group's business activities and by avoiding risks of human rights violations.
  </p><!-- テキストはここを編集 -->
</div>

<!-- item1 ここから -->
<div class="c-h3-a">
  <h3 class="c-h3-a__text">Ricoh Group’s Human Rights Policy</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">In April 2021, the Ricoh Group established the “Ricoh Group’s Human Rights Policy” in accordance with the “United Nations Guiding Principles on Business and Human Rights.” This policy was formulated based on the opinions of experts inside and outside the company and was deliberated by the ESG Committee *. It is a commitment of the Ricoh Group to respect the human rights of all people, which was approved by the CEO of Ricoh. We had been respecting human rights in accordance with the Ricoh Group Code of Conduct, but we strengthened our efforts based on this human rights policy to comply with international standards, taking into consideration the widening range of human rights issues in the international community. The Policy is positioned at the top of all human rights-related standards and regulations within the Ricoh Group, with its goal as the prevention of human rights violations.<br>
    This policy is translated into English and eight other languages and communicated for educational purposes to major group companies in Japan and overseas.<br>
    The Policy must be followed by all executives and employees of the Ricoh Group. Suppliers and all forms of business partners of the Ricoh Group are also requested to support and implement this policy.
  </p><!-- テキストはここを編集 -->
</div>

