  </h3>
  <section class="c-h4-a">
    <h4 class="c-h4-a__text">
      (1) Background of the initiatives
    </h4>
    <div class="c-text-a">
      <p class="c-text-a__text">
        Ricoh has been providing individual follow-ups to employees with mental health problems by industrial
        psychiatrists for
        more than 30 years. In addition, regular meetings among industrial psychiatrists, the human resources
        department, and
        the health and safety department have been held to ensure that more appropriate measures are taken to those
        employees.
        Since 2005, we have built a health management system for employees working long hours in conjunction with work
        management and overtime management to strengthen measures against overwork. At the same time, we have enhanced
        the
        system by adding clinical psychologists to industrial physicians, nurses and certified public psychologist.
      </p>
    </div>
  </section>
  <section class="c-h4-a">
    <h4 class="c-h4-a__text">
      (2) Self-care
    </h4>
    <div class="c-text-a">
      <p class="c-text-a__text">
        In 2007, Ricoh was one of the first to introduce stress checks, which later became mandatory legislation, and in
        2009, we provided self-care e-learning to all Ricoh Group and new employees. In addition, we are working to
        create an environment where employees can work with peace of mind by providing an easy access to online
        counseling services. In addition, for employees transferred overseas, in consideration of working and living
        environments that differ significantly from those in Japan and the health support system in the new location, we
        conduct interviews with the occupational health staff in charge of overseas operations and lectures on mental
        health by occupational physicians prior to their transfer to the new location.
      </p>
    </div>
  </section>
  <section class="c-h4-a">
    <h4 class="c-h4-a__text">
      (3) Line Care
    </h4>
    <div class="c-text-a">
      <p class="c-text-a__text">
        In 2006, we started e-learning for all organizational managers to learn the basics of HR and labor management
        and the fundamentals of line care, as well as training in attentive listening to ensure smooth communication
        with team members, as part of our efforts to prevent overtime work. Since then, the training has been conducted
        on an annual basis for newly appointed organization managers.
      </p>
      <p class="c-text-a__text">
        Since 2011, we have conducted workplace management training by industrial physicians to learn how to manage
        employees with mental health problems based on case studies, providing an opportunity to learn how to manage
        such
        employees and to strengthen cooperation between industrial physicians and organization managers.
      </p>
      <p class="c-text-a__text">
        Since 2017, we have begun to expand the program to Ricoh Group companies, and are regularly conducting line care
        training for organizational positions other than newly appointed employees.
      </p>
      <p class="c-text-a__text">
        In fiscal 2020, we will conduct more practical online interactive line care training, taking into account the
        increasing use of remote work in a variety of positions. The training is designed to provide an opportunity for
        participants to discuss and receive advice on line care directly from industrial physicians.
      </p>
