<div class="c-h3-a">
  <h3 class="c-h3-a__text">Activity policy regarding external organizations (industry groups/initiatives)</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Ricoh Group will engage in proactive policy advocacy activities through external
    organizations and initiatives to realize its approach and strategy for addressing climate change. In cases where
    there is a discrepancy between Ricoh Group's position and approach to climate change and the stance or activities of
    the participating organizations or initiatives, or if there are perceived shortcomings in climate change mitigation
    within those organizations or initiatives, Ricoh Group will collaborate with other companies to advocate for
    strengthened measures. Additionally, we will regularly verify the consistency and alignment of activities between
    Ricoh Group's climate change strategy and external organizations or initiatives, and if significant deficiencies or
    discrepancies are found, it will consider the possibility of withdrawing from the respective organization or
    initiative.</p><!-- テキストはここを編集 -->
