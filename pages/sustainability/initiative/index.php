<div class="c-h3-a">
  <h3 class="c-h3-a__text">Basic Policy</h3>
</div>

<div class="c-text-a">
  <p class="c-text-a__text">Since advocating environmental management in 1998, Ricoh Group has been working on climate
    change measures from a scientific perspective in line with international treaties and bodies such as The Paris
    Agreement and IPCC. We prioritize these basic measures that guide us in our drive to introduce necessary climate
    change policies and activate corporate climate change measures by participating in domestic and international
    initiatives on climate change that go beyond the scope of existing economic or industry organizations.</p>
