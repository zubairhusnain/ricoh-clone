                                <div class="c-text-a">
  <p class="c-text-a__text">The founder of the Ricoh Group, Kiyoshi Ichimura, established the Spirit of Three Loves— “Love your neighbor” “Love your country” “Love your work” —as the unwavering foundation of Ricoh’s corporate activities. Our approach of placing ESG and business activities on the same axis carries forward this spirit and serves as a guiding principle for our decisions and actions.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">We position our ESG targets as “Future Financial Targets,” believing that the ESG initiatives undertaken to achieve them will drive long-term growth. Through our business, we create value for society, and that value helps to sustainably enhance people’s well-being. As society becomes more sustainable, companies are also able to grow. We believe that by continuing this cycle, we build trust as a company.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Through this positive cycle of value creation, the Ricoh Group aims to continue earning the trust of all stakeholders and to remain their company of choice.</p>
