                                </div>
                            </div>
                                                    <div class="c-linkCard__textwrap">
                                <div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group is committed to the responsible utilization of data, enabling customers to take advantage of digital technologies with confidence and peace of mind.</p>
  <p class="c-text-a__text">As a foundational guideline for this purpose, the Ricoh Group has established the Ricoh Group Data Governance Policy.</p>
