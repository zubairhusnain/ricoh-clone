                                                    <div class="c-linkCard__textwrap">
                                <div class="c-h4-a">
  <h4 class="c-h4-a__text">1. Data Utilization</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group regards data as an important asset that contributes to the creation of new customer value and actively utilizes it through cross-organizational sharing and collaboration, including the use of advanced technologies such as AI.<br>When utilizing data, the Ricoh Group complies with the principles outlined in Sections 2 through 4 below.</p>
</div>
<div class="c-h4-a">
  <h4 class="c-h4-a__text">2. Data Security and Privacy Protection</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Ensuring the security and safety of customer information is one of the Ricoh Group's highest priorities. The Ricoh Group complies with applicable laws and regulations, as well as its Data Privacy Policy, and places top priority on ensuring the confidentiality, integrity, and availability of data.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">To achieve this, appropriate security measures—including encryption, access control, and vulnerability management—are applied and continuously improved. When handling personal information, the Ricoh Group complies with all applicable laws and regulations and operates with a strong emphasis on privacy protection.</p>
</div>
