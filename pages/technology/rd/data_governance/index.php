      <div class="c-attention-a__marker"><span>*</span></div>
      <div class="c-attention-a__text">The Data Privacy Policy defines the rules for protecting data (information), while the Data Governance Policy defines the rules for utilizing data.</div>
    </li>
  </ul>
</div>
<div class="c-h4-a">
  <h4 class="c-h4-a__text">3. Assurance of Data Quality</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group has established quality control processes to maintain the accuracy, consistency, and integrity of data. An appropriate data environment is maintained through validation at the time of data entry and the periodic cleansing of data.</p>
</div>
<div class="c-h4-a">
  <h4 class="c-h4-a__text">4. Compliance and the Technology Ethics Charter</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">The Ricoh Group complies with all applicable laws and regulations in Japan and overseas and observes compliance across all processes related to the acquisition, use, and storage of data.</p>
