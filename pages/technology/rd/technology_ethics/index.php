                                                    <div class="c-linkCard__textwrap">
                                <div class="c-h4-a">
  <h4 class="c-h4-a__text">1. Research Ethical Review Board System</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">The Research Ethical Review Board System has been introduced for research functions conducted by Ricoh Group companies in Japan. This system aims to ensure that research is properly conducted from both ethical and scientific viewpoints. It covers ergonomic research in addition to medical research involving human subjects. In recent years, as data-utilizing prototyping demonstration experiments and societal implementation have become more common, the scope of the research ethics review system has been expanded to include not only research functions but also development functions.</p>
  <p class="c-text-a__text">The Ricoh Ethics Review Committee, which includes outside experts, has been established to ensure fair reviews under this system.</p>
</div>
