<div class="c-h4-a">
  <h4 class="c-h4-a__text">2. Risk Management Process</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Research function departments conducting research involving human subjects are working to predict the impacts of ELSI beginning in the initial stages of research and to incorporate, in advance, appropriate countermeasures in designs. To ensure the effectiveness of these initiatives—known as “ELSI by Design"—we have introduced a risk management process (RMP) that involves reviews that incorporate the opinions of third parties.</p>
</div>
<div class="c-link-a-list u-mt-0">
