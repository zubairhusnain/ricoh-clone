<div class="c-h4-a">
  <h4 class="c-h4-a__text">3. Technology Assessments</h4>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">It is necessary to integrate a research ethics review system and agile development steps to deal with ELSI, which has come under greater scrutiny by society due to the rapid development of new technologies, particularly AI technologies. We have introduced Technology Assessment (TA) to bridge this gap.</p>
  <p class="c-text-a__text">With TA, developers conduct risk analyses in response to multiple ELSI target elements (TA items) that are identified in a comprehensive manner, then plan and implement countermeasures. Third-party assessors review the results in terms of assessing risks at the time of application and the effectiveness of the countermeasures (including plans for the next step). Developers and assessors of products and services follow agile development and conduct iterative TA as necessary from the initial stages of development to control risks prior to launch.</p>
