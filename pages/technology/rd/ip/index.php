                                                    <div class="c-linkCard__textwrap">
                                <div class="c-text-a">
  <p class="c-text-a__text">Ricoh’s intellectual property activities began with a camera patent application in 1947. The patent management section was first organized in 1958 when the first person dedicated to patents was assigned. The intellectual property department has then expanded and strengthened as Ricoh business grew exponentially over the intervening decades.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Our Intellectual Property Center comprises the Intellectual Property Development Department and the Intellectual Property Strategy Department. These departments are respectively tasked with patent prosecution, external affairs and licensing.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Intellectual property workers keep close contact with their colleagues in research and development so as to apply for patents and establish rights as soon as possible.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">To acquire valuable intellectual property suitable for individual markets timely and speedily, we have staffed an intellectual property organization in major R&amp;D centers. By doing so, we have the capability to carry out on-site based intellectual property activities with no time lag.</p>
</div>
                            </div>
