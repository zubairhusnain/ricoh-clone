            <div class="c-margin-b__inner">
                    <div class="c-h2-a">
                        <h2 class="c-h2-a__text">Our efforts to improve organizational ability for supporting intellectual property activity</h2>
                    </div>
                    <div class="c-multiCol">
        <div class="c-linkCard c-linkCard--col1 c-linkCard--col1-wide">
            
                <div class="c-linkCard__item c-linkCard__item--layout1">
                    <div class="c-linkCard__inner">
                                                    <div class="c-linkCard__textwrap">
                                <div class="c-text-a">
  <p class="c-text-a__text">We continually provide various incentive schemes to encourage inventors for the long term, focusing on high quality intellectual property creation and patent acquisition. Moreover, to improve intellectual property skills in technical divisions, we work to raise the level of the overall intellectual property ability, implementing intellectual property education suited to engineers' years of experience, assigning experienced persons to lecture on intellectual property.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">We have prepared training programs for persons tasked with intellectual property activities. Examples are an educational system for persons newly assigned to intellectual property work, and an OJT (On-the-Job Training) program to improve individual intellectual property skills. Beyond our short-term residence system to overseas patent office and a long-term foreign posting system to overseas Ricoh offices, we also provide the opportunity to apply and prosecute patents through direct communication with overseas lawyers. The purpose is to improve global intellectual property skills.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">In the Intellectual Property Center, we also collect, coordinate, analyze, and process massive intellectual property data efficiently and quickly, and then combine that information with other data besides intellectual property. Ultimately, the comprehensive information is used to formulate intellectual property strategies and proposals to business divisions or managements, aiming at maximizing the value of intellectual property.</p>
</div>
<div class="c-text-a">
  <p class="c-text-a__text">Concentrating all intellectual property activities for the purpose of “contribution to business,” we continue to aim at building a more efficient and enhanced intellectual property system.</p></div>
