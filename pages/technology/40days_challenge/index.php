                                </div>
                            </div>
                                                    <div class="c-linkCard__textwrap">
                                <div class="c-text-a">
<p class="c-text-a__text">The goal was to see how many bowling pins placed 25 meters away could be knocked down by a DVD launched by pressing a DVD player’s eject button after playing for 30 seconds or more. Ricoh took on the challenge, making full use of its analytical technology combined with its expertise in paper transport technology used in copiers/printers (multifunction printers).</p>
