<p class="c-text-a__text">The THOOTA-R name comes from the wish to achieve a trajectory similar to a soccer shot. That aim started the development; the device was initially nicknamed “Shooter-kun” by team members. THOOTA also infers an affinity to the well-loved RICOH THETA series of spherical cameras. And finally, an R was added for “Ricoh,” or as a machine that shoots a DVD-“R.”</p>
